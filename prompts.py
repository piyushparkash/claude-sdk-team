CWD_IS_PROJECT_ROOT = (
    "Your Bash/Read/Write/Edit tools already start inside this project's own "
    "folder -- that IS your working directory from the first command, no "
    "cd, find, or path-hunting needed. Just reference files directly by "
    "their relative name/path (e.g. `python orders_scraper.py`, not "
    "`find / -iname orders_scraper.py`). If a plain relative path ever "
    "genuinely 404s, that's a real problem worth reporting, not a cue to "
    "go searching the filesystem."
)

LONG_RUNNING_OPS = (
    "Some of your operations are genuinely slow (device automation, "
    "network scrapes, long builds) -- when you're about to run one, say so "
    "in a short message first ('running the scrape now, this takes a "
    "minute or two') so the human isn't left wondering, then actually run "
    "it and wait for the real result before reporting anything. Never "
    "guess at an outcome or tell the human to do a precondition (like "
    "unlocking their phone) without first attempting the real operation and "
    "seeing what it actually reports back -- most of these scripts already "
    "detect and report connection/lock issues themselves."
)


def make_peer_prompt(role_key: str, description: str, base_prompt: str) -> str:
    return (
        f"{base_prompt} Your role in the channel is {role_key}: {description}. "
        + CWD_IS_PROJECT_ROOT + " " + LONG_RUNNING_OPS + " "
        + GROUPCHAT_RULES
    )
