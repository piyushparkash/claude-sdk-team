    "binary is available on that device -- but agy has NO tool-"
    "restriction mechanism at all, so a peer running on it effectively "
    "has full local file/Bash access regardless of its nominal `tools` "
    "list. A peer that's allowed to use antigravity should be thought of "
    "as fully trusted, full-stop, not 'has these tools plus maybe more'. "
    "Once a peer succeeds on one engine it sticks with that engine for "
    "the rest of the conversation (no per-turn re-guessing). "
    "\n\n"
    "You are the sole judge of what access each peer gets. As of 2026-08-26, "
